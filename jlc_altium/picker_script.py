"""Generates the Altium part picker (DelphiScript form: .pas + .dfm).

The Altium counterpart of kicad-jlcpcb-tools' part search window: select
components on a schematic, run JLCPCBPartPicker, search the JLCPCB
catalogue, and the chosen LCSC code is written to each component's "LCSC"
parameter. Searching is done by `python -m jlc_altium search --tsv`, so the
script only handles the window and the schematic.

Helpers are prefixed "Pk" because every unit in an Altium script project
shares one namespace with JLC_Setup.pas and JLC_Tools.pas.
"""

from __future__ import annotations

from .config import REPO_ROOT, Config

