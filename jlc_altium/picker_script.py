def _q(s) -> str:
    return "'" + str(s).replace("'", "''") + "'"


def render(cfg: Config, python: str) -> str:
    return PICKER_PAS % {
        "repo": _q(REPO_ROOT),
        "python": _q(python),
        "results": _q((cfg.output_dir / "Altium" / "picker_results.tsv").resolve()),
        "sizes": _q(PREFILL_SIZES),
    }
