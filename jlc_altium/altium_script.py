"""Generates the one-time Altium setup script (DelphiScript).

Altium can only create .SchLib/.PcbLib files and install libraries from
inside Altium, so `setup` writes a script with this machine's paths baked
in. Running it once (File » Run Script) creates:

  library/Symbols/JLC_Generic.SchLib     Resistor, Capacitor, Inductor, Ferrite Bead
  library/Footprints/JLC_Generic.PcbLib  RES-/CAP-/IND-/FB- 0201..1210

and installs JLCPCB.DbLib and the PcbLib in the Components panel. Existing
library files are left untouched, so re-running it is safe.
"""

from __future__ import annotations

from pathlib import Path

from . import footprints
from .config import Config

SCRIPT_NAME = "JLC_Setup"

# Symbol name key in config -> (designator prefix, drawing procedure)
SYMBOLS = [
    ("resistor", "R", "DrawResistor"),
    ("capacitor", "C", "DrawCapacitor"),
    ("inductor", "L", "DrawInductor"),
    ("ferrite", "FB", "DrawFerrite"),
]


def _q(s: str) -> str:
    """Pascal string literal."""
    return "'" + str(s).replace("'", "''") + "'"


def _mm(v: float) -> str:
    return f"{v:.4f}"


TEMPLATE = r"""{ Generated by `python -m jlc_altium setup` - re-run setup to regenerate.

  Run once in Altium: File > Run Script > Browse > select this project
  (JLC_Setup.PrjScr), then choose the procedure "Setup".
}

Const
  DbLibPath  = %(dblib)s;
  SchLibPath = %(schlib)s;
  PcbLibPath = %(pcblib)s;

Var
  Log : String;

Procedure Note(S : String);
Begin
  Log := Log + S + #13#10;
End;

{ ---------- schematic symbols (coordinates in mils, pin ends on a 100 mil grid) ---------- }

Procedure AddObj(Comp : ISch_Component; Obj : ISch_GraphicalObject);
Begin
  Obj.OwnerPartId := 1;
  Obj.OwnerPartDisplayMode := 0;
  Comp.AddSchObject(Obj);
End;

Procedure AddLine(Comp : ISch_Component; X1, Y1, X2, Y2 : Integer);
Var L : ISch_Line;
Begin
  L := SchServer.SchObjectFactory(eLine, eCreate_Default);
  L.Location := Point(MilsToCoord(X1), MilsToCoord(Y1));
  L.Corner := Point(MilsToCoord(X2), MilsToCoord(Y2));
  L.LineWidth := eSmall;
  AddObj(Comp, L);
End;

Procedure AddRect(Comp : ISch_Component; X1, Y1, X2, Y2 : Integer; Solid : Boolean);
Var R : ISch_Rectangle;
Begin
  R := SchServer.SchObjectFactory(eRectangle, eCreate_Default);
  R.Location := Point(MilsToCoord(X1), MilsToCoord(Y1));
  R.Corner := Point(MilsToCoord(X2), MilsToCoord(Y2));
  R.LineWidth := eSmall;
  R.IsSolid := Solid;
  If Solid Then R.AreaColor := R.Color;
  AddObj(Comp, R);
End;

Procedure AddArc(Comp : ISch_Component; X, Y, Radius : Integer);
Var A : ISch_Arc;
Begin
  A := SchServer.SchObjectFactory(eArc, eCreate_Default);
  A.Location := Point(MilsToCoord(X), MilsToCoord(Y));
  A.Radius := MilsToCoord(Radius);
  A.StartAngle := 270;
  A.EndAngle := 90;
  A.LineWidth := eSmall;
  AddObj(Comp, A);
End;

Procedure AddPin(Comp : ISch_Component; Num : String; Y : Integer; Up : Boolean);
Var P : ISch_Pin;
Begin
  P := SchServer.SchObjectFactory(ePin, eCreate_Default);
  P.Location := Point(0, MilsToCoord(Y));
  If Up Then P.Orientation := eRotate90 Else P.Orientation := eRotate270;
  P.PinLength := MilsToCoord(100);
  P.Designator := Num;
  P.Name := Num;
  P.Electrical := eElectricPassive;
  P.ShowName := False;
  P.ShowDesignator := False;
  AddObj(Comp, P);
End;

Procedure DrawResistor(Comp : ISch_Component);
Begin
  AddRect(Comp, -40, -100, 40, 100, False);
End;

Procedure DrawCapacitor(Comp : ISch_Component);
Begin
  AddLine(Comp, -80, 20, 80, 20);
  AddLine(Comp, -80, -20, 80, -20);
  AddLine(Comp, 0, 100, 0, 20);
  AddLine(Comp, 0, -20, 0, -100);
End;

Procedure DrawInductor(Comp : ISch_Component);
Begin
  AddArc(Comp, 0, 75, 25);
  AddArc(Comp, 0, 25, 25);
  AddArc(Comp, 0, -25, 25);
  AddArc(Comp, 0, -75, 25);
End;

Procedure DrawFerrite(Comp : ISch_Component);
Begin
  AddRect(Comp, -40, -70, 40, 70, True);
  AddLine(Comp, 0, 100, 0, 70);
  AddLine(Comp, 0, -70, 0, -100);
End;

Procedure AddSymbol(Lib : ISch_Lib; Name, Prefix, Draw : String);
Var Comp : ISch_Component;
Begin
  Comp := SchServer.SchObjectFactory(eSchComponent, eCreate_Default);
  Comp.CurrentPartID := 1;
  Comp.DisplayMode := 0;
  If Draw = 'DrawResistor' Then DrawResistor(Comp);
  If Draw = 'DrawCapacitor' Then DrawCapacitor(Comp);
  If Draw = 'DrawInductor' Then DrawInductor(Comp);
  If Draw = 'DrawFerrite' Then DrawFerrite(Comp);
  AddPin(Comp, '1', 100, True);
  AddPin(Comp, '2', -100, False);
  Lib.AddSchComponent(Comp);
  Comp.LibReference := Name;
  Comp.Designator.Text := Prefix + '?';
  Comp.ComponentDescription := 'JLCPCB generic ' + Name;
End;

Procedure CreateSchLib;
Var
  Doc : IServerDocument;
  Lib : ISch_Lib;
  Placeholder : ISch_Component;
Begin
  If FileExists(SchLibPath) Then
  Begin
    Note('Symbols: kept existing ' + SchLibPath);
    Exit;
  End;
  Doc := CreateNewDocumentFromDocumentKind('SCHLIB');
  Client.ShowDocument(Doc);
  Lib := SchServer.GetCurrentSchDocument;
  If Lib = Nil Then
  Begin
    Note('Symbols: FAILED to create a schematic library');
    Exit;
  End;
  Placeholder := Lib.CurrentSchComponent;
  SchServer.ProcessControl.PreProcess(Lib, '');
%(symbols)s  If Placeholder <> Nil Then Lib.RemoveSchComponent(Placeholder);
  SchServer.ProcessControl.PostProcess(Lib, '');
  ForceDirectories(ExtractFilePath(SchLibPath));
  Doc.DoSafeChangeFileNameAndSave(SchLibPath, 'SCHLIB');
  Note('Symbols: created ' + SchLibPath);
End;

{ ---------- footprints (coordinates in mm) ---------- }

Procedure AddPad(Comp : IPCB_LibComponent; Board : IPCB_Board; Name : String; X, L, W : Double);
Var Pad : IPCB_Pad;
Begin
  Pad := PCBServer.PCBObjectFactory(ePadObject, eNoDimension, eCreate_Default);
  Pad.Mode := ePadMode_Simple;
  Pad.X := Board.XOrigin + MMsToCoord(X);
  Pad.Y := Board.YOrigin;
  Pad.TopXSize := MMsToCoord(L);
  Pad.TopYSize := MMsToCoord(W);
  Pad.TopShape := eRectangular;
  Pad.HoleSize := 0;
  Pad.Layer := eTopLayer;
  Pad.Name := Name;
  Comp.AddPCBObject(Pad);
  PCBServer.SendMessageToRobots(Comp.I_ObjectAddress, c_Broadcast, PCBM_BoardRegisteration, Pad.I_ObjectAddress);
End;

Procedure AddTrack(Comp : IPCB_LibComponent; Board : IPCB_Board; X1, Y1, X2, Y2 : Double);
Var T : IPCB_Track;
Begin
  T := PCBServer.PCBObjectFactory(eTrackObject, eNoDimension, eCreate_Default);
  T.X1 := Board.XOrigin + MMsToCoord(X1);
  T.Y1 := Board.YOrigin + MMsToCoord(Y1);
  T.X2 := Board.XOrigin + MMsToCoord(X2);
  T.Y2 := Board.YOrigin + MMsToCoord(Y2);
  T.Width := MMsToCoord(0.05);
  T.Layer := eMechanical15;
  Comp.AddPCBObject(T);
  PCBServer.SendMessageToRobots(Comp.I_ObjectAddress, c_Broadcast, PCBM_BoardRegisteration, T.I_ObjectAddress);
End;

Procedure AddChip(Lib : IPCB_Library; Name : String; L, W, Pitch, CX, CY : Double);
Var Comp : IPCB_LibComponent;
Begin
  Comp := PCBServer.CreatePCBLibComp;
  Comp.Name := Name;
  Comp.Description := 'JLCPCB generic chip ' + Name;
  Lib.RegisterComponent(Comp);
  AddPad(Comp, Lib.Board, '1', -Pitch / 2, L, W);
  AddPad(Comp, Lib.Board, '2', Pitch / 2, L, W);
  { courtyard outline on Mechanical 15 }
  AddTrack(Comp, Lib.Board, -CX, -CY, CX, -CY);
  AddTrack(Comp, Lib.Board, CX, -CY, CX, CY);
  AddTrack(Comp, Lib.Board, CX, CY, -CX, CY);
  AddTrack(Comp, Lib.Board, -CX, CY, -CX, -CY);
End;

Procedure CreatePcbLib;
Var
  Doc : IServerDocument;
  Lib : IPCB_Library;
  Placeholder : IPCB_LibComponent;
Begin
  If FileExists(PcbLibPath) Then
  Begin
    Note('Footprints: kept existing ' + PcbLibPath);
    Exit;
  End;
  Doc := CreateNewDocumentFromDocumentKind('PCBLIB');
  Client.ShowDocument(Doc);
  Lib := PCBServer.GetCurrentPCBLibrary;
  If Lib = Nil Then
  Begin
    Note('Footprints: FAILED to create a PCB library');
    Exit;
  End;
  Placeholder := Lib.CurrentComponent;
  PCBServer.PreProcess;
%(footprints)s  PCBServer.PostProcess;
  If Placeholder <> Nil Then Lib.RemoveComponent(Placeholder);
  ForceDirectories(ExtractFilePath(PcbLibPath));
  Doc.DoSafeChangeFileNameAndSave(PcbLibPath, 'PCBLIB');
  Note('Footprints: created ' + PcbLibPath);
End;

{ ---------- install ---------- }

Procedure Install(Path : String);
Var I : Integer;
Begin
  For I := 0 To IntegratedLibraryManager.InstalledLibraryCount - 1 Do
    If SameText(IntegratedLibraryManager.InstalledLibraryPath(I), Path) Then
    Begin
      Note('Installed already: ' + Path);
      Exit;
    End;
  IntegratedLibraryManager.InstallLibrary(Path);
  Note('Installed: ' + Path);
End;

Procedure Setup;
Begin
  Log := '';
  If Not FileExists(DbLibPath) Then
  Begin
    ShowMessage('Not found: ' + DbLibPath + #13#10 + 'Run setup.cmd first.');
    Exit;
  End;
  CreateSchLib;
  CreatePcbLib;
  Install(DbLibPath);
  If FileExists(PcbLibPath) Then Install(PcbLibPath);
  ShowMessage('JLCPCB library setup' + #13#10#13#10 + Log + #13#10 +
    'Open the Components panel and pick "JLCPCB" to start placing parts.');
End;
"""

PRJSCR = """[Design]
Version=1.0

[Document1]
DocumentPath=JLC_Setup.pas
"""


def render(cfg: Config) -> str:
    sym, fp = cfg.section("symbols"), cfg.section("footprints")
    symbols = "".join(
        f"  AddSymbol(Lib, {_q(sym.get(key, key.title()))}, {_q(prefix)}, {_q(draw)});\n"
        for key, prefix, draw in SYMBOLS)
    chips = []
    for fam in ("resistor", "capacitor", "inductor", "ferrite"):
        prefix = fp.get(fam, fam.upper())
        for size, ((pad_l, pad_w, pitch), _) in footprints.CHIP_LANDS.items():
            cx, cy = footprints.courtyard(size)
            chips.append(f"  AddChip(Lib, {_q(f'{prefix}-{size}')}, {_mm(pad_l)}, {_mm(pad_w)}, "
                         f"{_mm(pitch)}, {_mm(cx)}, {_mm(cy)});\n")
    return TEMPLATE % {
        "dblib": _q(cfg.dblib_path.resolve()),
        "schlib": _q(schlib_path(cfg).resolve()),
        "pcblib": _q(pcblib_path(cfg).resolve()),
        "symbols": symbols,
        "footprints": "".join(chips),
    }


def schlib_path(cfg: Config) -> Path:
    return cfg.output_dir / "Symbols" / cfg.section("symbols").get("library", "JLC_Generic.SchLib")


def pcblib_path(cfg: Config) -> Path:
    return cfg.output_dir / "Footprints" / (cfg.section("footprints").get("library") or "JLC_Generic.PcbLib")


def write(cfg: Config) -> Path:
    folder = cfg.output_dir / "Altium"
    folder.mkdir(parents=True, exist_ok=True)
    (folder / f"{SCRIPT_NAME}.pas").write_text(render(cfg), encoding="utf-8", newline="\r\n")
    (folder / f"{SCRIPT_NAME}.PrjScr").write_text(PRJSCR, encoding="utf-8", newline="\r\n")
    return folder / f"{SCRIPT_NAME}.PrjScr"
